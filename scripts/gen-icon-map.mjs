// Generates src/ui/icons.ts from Material Symbols (rounded, weight 400) so only used icons ship.
// Usage: add a name to ICONS below, then run `node scripts/gen-icon-map.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';

const ICONS = [
  'file_open', 'folder_open', 'note_add', 'save', 'save_as', 'download', 'undo', 'redo', 'content_cut', 'content_copy',
  'content_paste', 'delete', 'edit', 'edit_note', 'add', 'search', 'history', 'light_mode', 'dark_mode', 'help', 'info',
  'close', 'chevron_right', 'arrow_upward', 'arrow_downward', 'data_object', 'data_array', 'format_list_bulleted',
  'text_fields', 'counter_1', 'counter_2', 'counter_3', 'counter_4', 'decimal_increase', 'folder', 'description',
  'grid_view', 'deployed_code', 'public', 'lock', 'backup', 'sort_by_alpha', 'unfold_more', 'unfold_less', 'code',
  'manage_search', 'find_replace', 'fingerprint', 'error', 'warning', 'check_circle', 'progress_activity', 'upload_file', 'keyboard',
  'more_vert', 'travel_explore', 'my_location', 'block', 'tab', 'filter_list', 'tune', 'contrast', 'schedule',
  'open_in_new', 'select_all', 'difference', 'account_tree', 'category', 'package_2', 'conversion_path',
  'bottom_panel_open', 'bottom_panel_close', 'library_add', 'playlist_add', 'swap_horiz', 'texture', 'view_in_ar',
];

const dir = 'node_modules/@material-symbols/svg-400/rounded/';
const lines = [];
for (const name of ICONS) {
  for (const variant of ['', '-fill']) {
    let svg;
    try { svg = readFileSync(dir + name + variant + '.svg', 'utf8'); } catch { if (!variant) throw new Error('missing ' + name); continue; }
    const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
    lines.push(`  ${JSON.stringify(name + variant)}: ${JSON.stringify(paths.join(' '))},`);
  }
}
writeFileSync(
  'src/ui/icons.ts',
  `// GENERATED by scripts/gen-icon-map.mjs — Material Symbols Rounded (Apache-2.0), viewBox "0 -960 960 960".\n` +
    `export const ICONS: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
console.log('wrote', lines.length, 'icons');
